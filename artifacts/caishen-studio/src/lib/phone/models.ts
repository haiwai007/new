export type PhoneModelId = (typeof PHONE_MODELS)[number]["id"];
export const PHONE_BRANDS = [
  ...new Set(PHONE_MODELS.map((model) => model.brand)),
];
export function phoneModel(id: PhoneModelId) {
  const model = PHONE_MODELS.find((m) => m.id === id);
  if (!model) throw new Error("不支持的手机型号");
  return model;
}
