export type PhoneSystem =
  | "ios"
  | "classic"
  | "pixel"
  | "oneui"
  | "oneui7"
  | "hyperos"
  | "harmony"
  | "magic"
  | "coloros"
  | "originos"
  | "realme";
function preset<const Id extends string>(
  id: Id,
  name: string,
  brand: string,
  system: PhoneSystem,
  width: number,
  height: number,
  points: number,
  bar: number,
  cutout: "island" | "notch" | "hole" | "pill" | "none" = "hole",
  cutoutPosition: "center" | "left" = "center",
) {
  return {
    id,
    name,
    brand,
    system,
    width,
    height,
    points,
    bar,
    style:
      system === "ios"
        ? ("ios" as const)
        : system === "classic"
          ? ("classic" as const)
          : ("android" as const),
    cutout,
    cutoutPosition,
    cutoutWidth:
      cutout === "island"
        ? 126
        : cutout === "notch"
          ? 160
          : cutout === "pill"
            ? 72
            : cutout === "none"
              ? 1
              : 12,
    cutoutHeight:
      cutout === "island"
        ? 35
        : cutout === "notch"
          ? 30
          : cutout === "pill"
            ? 16
            : cutout === "none"
              ? 1
              : 12,
  };
}
